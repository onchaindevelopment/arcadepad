export type IconName = keyof typeof ICONS;

export function PixelIcon({ name, size = 40, color = "#fff", className = "" }: { name: IconName; size?: number; color?: string; className?: string }) {
  const g = ICONS[name];
  return (
    <svg viewBox="0 0 12 12" width={size} height={size} shapeRendering="crispEdges" aria-hidden className={className}>
      {g.flatMap((row, y) => row.split("").map((c, x) => (c === "#" ? <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={color} /> : null)))}
    </svg>
  );
}
