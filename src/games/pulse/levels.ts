/*
 * Pulse Run levels: original, hand-designed for ArcadePad (GPL-3.0-or-later).
 *
 * A level is a list of chunks laid side by side. A chunk is a list of rows
 * (top to bottom); its LAST row is the ground row (row 10), the rows above it
 * stack upwards (row 9, 8, ...). Row 11 copies the ground. Short rows are
 * padded with "." (ground rows with "#").
 *
 *   #  solid block (land on top, crash into the side)
 *   ^  spike on the floor of its tile     v  spike hanging from the tile top
 *   p  jump pad                           o  jump orb (tap while touching)
 *   G  gravity flip portal (fall up)      N  normal gravity portal
 *   S  ship portal                        C  back-to-cube portal
 *   .  empty (a "." in the ground row is a pit)
 */
export const T = 30;
export const ROWS = 12;
/** The level is cleared when the player passes this many tiles before the end. */
export const FINISH_TAIL = 8;

export interface Portal {
  c: number;
  r: number;
  kind: "G" | "N" | "S" | "C";
}

export interface Level {
  name: string;
  cols: number;
  rows: string[];
  /** Player x at which the level counts as cleared. */
  endX: number;
  portals: Portal[];
}

const R = (n: number) => "#".repeat(n);

function build(name: string, chunks: (string | string[])[]): Level {
  const rows: string[] = Array.from({ length: ROWS }, () => "");
  for (const ch of chunks) {
    const lines = typeof ch === "string" ? ch.split("/") : ch;
    const w = Math.max(...lines.map((l) => l.length));
    const top = 10 - (lines.length - 1);
    for (let r = 0; r < ROWS; r++) {
      let s: string;
      if (r === 11) s = lines[lines.length - 1].padEnd(w, "#").replace(/[^#]/g, ".");
      else if (r >= top && r <= 10) s = lines[r - top].padEnd(w, r === 10 ? "#" : ".");
      else s = ".".repeat(w);
      rows[r] += s;
    }
  }
  const cols = rows[0].length;
  const portals: Portal[] = [];
  for (let r = 0; r < ROWS; r++) {
    for (let c = 0; c < cols; c++) {
      const k = rows[r][c];
      if (k === "G" || k === "N" || k === "S" || k === "C") portals.push({ c, r, kind: k });
    }
  }
  return { name, cols, rows, endX: (cols - FINISH_TAIL) * T, portals };
}

