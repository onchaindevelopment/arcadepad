/** Byte angle (any integer, wraps) -> sine. 0 = +x axis, 64 = +y (down on screen). */
export function sin256(a: number): number {
  return SIN256[a & 255];
}
export function cos256(a: number): number {
  return SIN256[(a + 64) & 255];
}

/**
 * Vector -> nearest byte angle, using only comparisons and arithmetic
 * (binary search over the octant with tangent comparisons).
 */
export function angle256(x: number, y: number): number {
  if (x === 0 && y === 0) return 0;
  // Fold into the first octant.
  const ax = x < 0 ? -x : x;
  const ay = y < 0 ? -y : y;
  const swap = ay > ax;
  const big = swap ? ay : ax;
  const small = swap ? ax : ay;
  // Find k in 0..32 with tan(k*2pi/256) closest to small/big.
  let best = 0;
  let bestErr = Infinity;
  for (let k = 0; k <= 32; k++) {
    const err = Math.abs(small * cos256(k) - big * sin256(k));
    if (err < bestErr) {
      bestErr = err;
      best = k;
    }
  }
  let a = swap ? 64 - best : best;
  if (x < 0) a = 128 - a;
  if (y < 0) a = 256 - a;
  return a & 255;
}
