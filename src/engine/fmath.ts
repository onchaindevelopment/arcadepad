/** Length of a 2D vector. */
export function vlen(x: number, y: number): number {
  return Math.sqrt(x * x + y * y);
}

/** Integer degrees (0..90) of atan(r) for r >= 0, LBreakout2 6.28-rad units. */
function atanDegrees(r: number): number {
  let lo = 0;
  let hi = TAN_STEPS.length; // answer in [0, 90]
  while (lo < hi) {
    const mid = (lo + hi + 1) >> 1;
    if (r >= TAN_STEPS[mid - 1]) lo = mid;
    else hi = mid - 1;
  }
  return lo;
}

/**
 * Port of LBreakout2 vec2angle(): direction of (x, y) as an impact-vector
 * index 0..179 (0 = right, clockwise with y pointing down).
 */
export function vec2angle(x: number, y: number): number {
  let degrees: number;
  if (x === 0) degrees = 90;
  else degrees = atanDegrees(Math.abs(y) / Math.abs(x));
  if (x > 0) {
    if (y < 0) degrees = 360 - degrees;
  } else {
    if (y >= 0) degrees = 180 - degrees;
    else degrees = 180 + degrees;
  }
  const a = degrees >> 1;
  return a >= 180 ? a - 180 : a;
}
